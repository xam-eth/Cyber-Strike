#!/usr/bin/env python3
"""Build the X11/GL stub shared libraries the pip `bpy` wheel dlopen()s.

The Blender-as-a-Python-module wheel links against X11/GL stacks that a
headless CI/sandbox image does not ship. Everything it actually calls at
import time is trivial; the rest is lazy-bound and never touched headless.
This script:

  1. reads the wheel's missing DT_NEEDED sonames (`ldd ... | grep 'not found'`);
  2. collects the undefined symbols of `bpy/__init__.so` and `libusd_ms.so`;
  3. emits one stub .so per family (SONAME-correct) into tools/.cache/x11stubs,
     with the quirks the linker/loader demands:
       - libGL implements the GLX/gl names it binds eagerly (return 0);
       - libXi exports the device hooks and the `_XiGetDevicePresenceNotifyEvent`
         data symbol (an int variable, not a function);
       - libxkbcommon exposes its symbols versioned `@V_0.5.0` via __asm__
         .symver plus a version script, or ld.so's check_match asserts.

    python3 tools/build_x11stubs.py

Then run python with `LD_LIBRARY_PATH=$PWD/tools/.cache/x11stubs`.
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENV = os.path.join(ROOT, ".venv")
OUT = os.path.join(ROOT, "tools", ".cache", "x11stubs")

# soname -> (symbol prefixes, needs versioning, extra data symbols, force-include)
FAMILIES = {
    "libGL.so.1": (["gl", "GL", "glX", "GLX", "egl", "EGL"], False, [], ["glFinish"]),
    "libXrender.so.1": (["XRender", "XGlyph"], False, [], []),
    "libXfixes.so.1": (["XFixes"], False, [], []),
    "libICE.so.6": (["Ice"], False, [], []),
    "libSM.so.6": (["SM"], False, [], []),
    "libXi.so.6": (
        ["XI", "Xi", "_Xi", "XOpenDevice", "XCloseDevice", "XListInputDevices",
         "XFreeDeviceList", "XFreeDeviceState", "XQueryDeviceState",
         "XSelectExtensionEvent", "XGetExtensionVersion"],
        False, ["_XiGetDevicePresenceNotifyEvent"], [],
    ),
    "libxkbcommon.so.0": (["xkb", "Xkb"], True, [], []),
}


def find_bpy() -> str:
    for base, _dirs, files in os.walk(os.path.join(VENV, "lib")):
        if "bpy" in base and "__init__.so" in files and "site-packages" in base:
            return os.path.join(base, "__init__.so")
    raise SystemExit("bpy/__init__.so not found under .venv — pip install bpy first")


def undefined_symbols(paths):
    names = set()
    for path in paths:
        out = subprocess.run(
            ["nm", "-D", "--undefined-only", path], capture_output=True, text=True, check=True
        ).stdout
        for line in out.splitlines():
            parts = line.split()
            if parts:
                # strip glibc-style versioned requirements (name@GLIBC_x.y)
                names.add(re.sub(r"@.+$", "", parts[-1]))
    return names


GL_RE = re.compile(r"^(gl[A-Z]|glX|GLX|GL[A-Z]|egl[A-Z])")


def main() -> int:
    bpy_so = find_bpy()
    usd = os.path.join(os.path.dirname(bpy_so), "lib", "libusd_ms.so")
    if not os.path.exists(usd):
        usd = os.path.join(os.path.dirname(bpy_so), "bpy", "lib", "libusd_ms.so")
    ldd = subprocess.run(["ldd", bpy_so], capture_output=True, text=True).stdout
    missing = sorted(
        m.group(1)
        for m in re.finditer(r"=>\s+not found\s+\((.+?)\)", ldd)
    )
    if not missing:
        missing = sorted(
            line.split()[0]
            for line in ldd.splitlines()
            if "not found" in line
        )
    print("missing sonames:", missing)
    syms = undefined_symbols([p for p in (bpy_so, usd) if os.path.exists(p)])
    os.makedirs(OUT, exist_ok=True)

    for soname in missing:
        key = next((k for k in FAMILIES if k.split(".so")[0] == soname.split(".so")[0]), soname)
        prefixes, versioned, data_syms, force = FAMILIES.get(key, ([], False, [], []))
        chosen = sorted(
            s for s in syms
            if (
                (GL_RE.match(s) if soname == "libGL.so.1"
                 else any(s.startswith(p) for p in prefixes))
            )
            and s not in data_syms
        )
        for f in force:
            if f not in chosen:
                chosen.append(f)
        stem = soname.split(".so")[0].replace("lib", "", 1)
        c_path = os.path.join(OUT, f"{stem}_stub.c")
        lines = ["/* generated by tools/build_x11stubs.py */"]
        for s in chosen:
            lines.append(f"void* {s}(void) {{ return 0; }}")
            if versioned:
                lines.append(f'__asm__(".symver {s},{s}@V_0.5.0");')
        for d in data_syms:
            lines.append(f"int {d} = 0;")
        with open(c_path, "w") as fh:
            fh.write("\n".join(lines) + "\n")
        so_path = os.path.join(OUT, soname)
        cmd = ["gcc", "-shared", "-fPIC", "-o", so_path, c_path, f"-Wl,-soname,{soname}"]
        if versioned:
            ver = os.path.join(OUT, f"{stem}.ver")
            with open(ver, "w") as fh:
                fh.write("V_0.5.0 {\n  global: *;\n};\n")
            cmd.append(f"-Wl,--version-script,{ver}")
        subprocess.run(cmd, check=True)
        print(f"built {so_path}: {len(chosen)} funcs, {len(data_syms)} data"
              f"{' , versioned V_0.5.0' if versioned else ''}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
