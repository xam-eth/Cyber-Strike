#!/usr/bin/env node
/**
 * slice_setpieces.mjs — cut the real Power Plant file into reusable set pieces.
 *
 * The Power Plant (`game/assets/world/real/powerplant.glb`) is one 42 MB scene of
 * 285 real meshes with 79 PBR materials and 65 baked 1024 px maps. Its individual
 * pieces — a tank, a container, an arch rib, a cooling tower, a column — are
 * authored, textured geometry that the world needs as standalone props.
 *
 * This script does **not** model anything. It copies the existing nodes, their
 * materials, textures and accessor data into smaller GLB files (prune + dedup), so
 * every piece still comes from the same licensed source, pixel for pixel.
 *
 *   node tools/asset-forge/real/slice_setpieces.mjs
 *
 * Output: game/assets/world/real/setpieces/<name>.glb + a JSON report.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { NodeIO } from '@gltf-transform/core';
import { prune, dedup, textureCompress } from '@gltf-transform/functions';

const ROOT = '/home/user/Cyber-Strike';
const SRC = path.join(ROOT, 'game/assets/world/real/powerplant.glb');
const OUT = path.join(ROOT, 'game/assets/world/real/setpieces');

/**
 * name → the node-name prefixes that make up the piece.
 * Prefixes are the real author's node names (mesh_<n>_Mesh_<type><n>_subset_<n>).
 */
const PIECES = {
  // 29.95 × 4.43 × 29.89 m — the round storage tank / silo top ring
  tank_ring: ['tank_a'],
  // 34.34 × 0.3 × 34.34 m — the big circular tank pad
  tank_pad: ['big_tank'],
  // 50 × 27.9 × 48 m — the cooling tower shell with fins
  cooling_tower: ['cool_tower_fins'],
  // 22.5 × 13.9 × 22.5 m — the tall arch portal
  tall_arch: ['tall_arch'],
  // 33.6 × 12.3 × 19.2 m — the six structural columns as one cluster
  columns: ['column'],
  // one column on its own (mesh_167), 0.6 m across
  column: ['mesh_167_Mesh_column_'],
  // 3.4 × 2.1 × 3.8 m — the parked drone, a nice small real prop
  drone: ['uav'],
  // 6.2 × 3.4 × 79.9 m — one crane carriage, used as an overhead gantry
  crane: ['crane_main', 'crane_clamp_b'],
};

const io = new NodeIO();
const source = await io.read(SRC);
const report = {};
fs.mkdirSync(OUT, { recursive: true });

const matches = (name, tokens) => tokens.some((t) => name.includes(t));

for (const [piece, tokens] of Object.entries(PIECES)) {
  const doc = await io.read(SRC); // fresh read per piece: cheap enough, and no cross-talk
  const root = doc.getRoot();
  const kept = [];
  let scene = root.listScenes()[0];

  // Drop every node that does not match, then prune what became unreachable.
  const stack = [...scene.listChildren()];
  while (stack.length) {
    const node = stack.pop();
    const name = node.getName() ?? '';
    const meshNode = node.getMesh() != null;
    if (meshNode && !matches(name, tokens)) {
      node.dispose();
      continue;
    }
    if (meshNode) kept.push(name);
    stack.push(...node.listChildren());
  }

  await doc.transform(prune(), dedup());

  const outFile = path.join(OUT, `${piece}.glb`);
  await io.write(outFile, doc);

  // Measure what actually survived, from the file we just wrote.
  const check = await io.read(outFile);
  const box = { min: [Infinity, Infinity, Infinity], max: [-Infinity, -Infinity, -Infinity] };
  for (const mesh of check.getRoot().listMeshes()) {
    for (const prim of mesh.listPrimitives()) {
      const pos = prim.getAttribute('POSITION');
      if (!pos) continue;
      const min = pos.getMin([]);
      const max = pos.getMax([]);
      for (let i = 0; i < 3; i += 1) {
        box.min[i] = Math.min(box.min[i], min[i]);
        box.max[i] = Math.max(box.max[i], max[i]);
      }
    }
  }
  const size = box.max.map((v, i) => +(v - box.min[i]).toFixed(2));
  const bytes = fs.statSync(outFile).size;
  report[piece] = {
    nodes: kept.length,
    meshes: check.getRoot().listMeshes().length,
    materials: check.getRoot().listMaterials().length,
    textures: check.getRoot().listTextures().length,
    size,
    min: box.min.map((v) => +v.toFixed(2)),
    bytes,
  };
  console.log(`${piece.padEnd(14)} ${String(kept.length).padStart(3)} nodes · ${size.join(' × ')} m · ${(bytes / 1048576).toFixed(1)} MB`);
}

fs.writeFileSync(path.join(OUT, 'setpieces.json'), `${JSON.stringify({
  note: 'Generated by tools/asset-forge/real/slice_setpieces.mjs from powerplant.glb (CC-BY-4.0, Kammertonus). Nodes, materials and baked textures are copied unchanged; nothing is modelled here.',
  source: 'game/assets/world/real/powerplant.glb',
  pieces: report,
}, null, 1)}\n`);
console.log(`report → ${path.relative(ROOT, path.join(OUT, 'setpieces.json'))}`);

// Refresh the provenance ledger so the new pieces are accounted for, with the
// same hash discipline as every downloaded file.
execFileSync(process.execPath, [path.join(ROOT, 'tools/asset-forge/real/fetch_real_assets.mjs'), '--write'], { stdio: 'inherit' });
console.log('provenance ledger rewritten for the new pieces');
