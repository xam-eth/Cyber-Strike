#!/usr/bin/env node
/**
 * gen_registry.mjs — derive `src/registry.js` from `catalog.json`.
 *
 * The registry is generated, never hand-maintained: a model that exists on disk
 * but is missing from the catalog (or the reverse) is a build error, not a
 * silently-hidden asset. Only entries whose module file exists are emitted; the
 * gate reports the rest as `missing-model` so a partial batch is visible.
 *
 *   node tools/asset-forge/gate/gen_registry.mjs
 *   node tools/asset-forge/gate/gen_registry.mjs --check   # exit 1 if stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..');
const FORGE = path.join(ROOT, 'tools', 'asset-forge');
const catalog = JSON.parse(fs.readFileSync(path.join(FORGE, 'catalog.json'), 'utf8'));

const CATEGORY_DIR = {
  world: 'world',
  hero: 'heroes',
  weapon: 'weapons',
  enemy: 'enemies',
  vfx: 'vfx',
};

const found = [];
const missing = [];
for (const entry of catalog.entries) {
  const dir = CATEGORY_DIR[entry.category];
  if (!dir) throw new Error(`catalog entry ${entry.id} has unknown category ${entry.category}`);
  const rel = `./${entry.module ?? `${dir}/${entry.id}.js`}`;
  const abs = path.join(FORGE, 'src', entry.module ?? `${dir}/${entry.id}.js`);
  if (fs.existsSync(abs)) found.push({ entry, rel, exportName: entry.exportName ?? 'build' });
  else missing.push(entry.id);
}

const lines = [];
lines.push('// GENERATED by tools/asset-forge/gate/gen_registry.mjs — do not edit by hand.');
lines.push('// Source: tools/asset-forge/catalog.json');
lines.push('');
for (const { entry, rel } of found) {
  lines.push(`import * as ${entry.id.replace(/[^a-zA-Z0-9_]/g, '_')} from '${rel}';`);
}
lines.push('');
lines.push('export const registry = {');
for (const { entry } of found) {
  const mod = entry.id.replace(/[^a-zA-Z0-9_]/g, '_');
  const exportName = entry.exportName ?? 'build';
  lines.push(`  ${JSON.stringify(entry.id)}: { name: ${JSON.stringify(entry.name)}, category: ${JSON.stringify(entry.category)}, load: () => Promise.resolve({ build: ${mod}.${exportName}, meta: ${mod}.metaById?.[${JSON.stringify(entry.id)}] ?? ${mod}.meta }) },`);
}
lines.push('};');
lines.push('');
lines.push('export const catalogOrder = ' + JSON.stringify(found.map((f) => f.entry.id), null, 2) + ';');
lines.push('');
lines.push('export const missingModels = ' + JSON.stringify(missing, null, 2) + ';');
lines.push('');
lines.push('export function categories() {');
lines.push('  const out = {};');
lines.push('  for (const [id, mod] of Object.entries(registry)) {');
lines.push('    (out[mod.category] ??= []).push(id);');
lines.push('  }');
lines.push('  return out;');
lines.push('}');
lines.push('');

const target = path.join(FORGE, 'src', 'registry.js');
const content = lines.join('\n');
const check = process.argv.includes('--check');
if (check) {
  const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (existing !== content) {
    console.error('registry.js is stale — run node tools/asset-forge/gate/gen_registry.mjs');
    process.exit(1);
  }
  console.log(`registry.js up to date (${found.length} models, ${missing.length} not built yet)`);
  process.exit(0);
}
fs.writeFileSync(target, content);
console.log(`wrote src/registry.js — ${found.length} models wired, ${missing.length} pending: ${missing.join(', ') || 'none'}`);
