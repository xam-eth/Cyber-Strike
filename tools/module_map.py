#!/usr/bin/env python3
"""Generate the module map in `docs/ARCHITECTURE.md` from the code itself.

Usage:
    tools/module_map.py             # print the map block to stdout
    tools/module_map.py --check     # exit 1 if docs/ARCHITECTURE.md is stale

Why this exists: a handover document that says where things live is only
useful while it is true, and the first thing a new owner does is read it. Map
written by hand drifts the moment somebody adds a folder; generated from the
tree, it cannot. `scripts/dev_check.sh` runs `--check`, so a pull that adds a
module without updating the map fails the same way a boundary violation does.

The classification is imported from `check_architecture.py` rather than
re-derived here, so the map and the boundary rule can never disagree about
which layer a file belongs to.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from check_architecture import DATA, FREE, GAME, classify  # noqa: E402

DOC = Path(__file__).resolve().parent.parent / "docs" / "ARCHITECTURE.md"
START = "<!-- module-map:start -->"
END = "<!-- module-map:end -->"

# Folders that are not modules a newcomer needs to find: tests live outside
# game/ on purpose, and the QA rig is developer tooling.
SKIP_PREFIXES = ("scripts/qa",)


def module_of(rel: str) -> str:
    """The module a file belongs to: its folder, or `scripts` at the root."""
    parts = rel.split("/")
    if len(parts) <= 2:
        return "scripts"
    return "/".join(parts[:-1])


def collect() -> dict[str, dict]:
    files = sorted(p for p in GAME.rglob("*.gd") if ".godot" not in p.parts)
    modules: dict[str, dict] = {}
    for path in files:
        rel = path.relative_to(GAME).as_posix()
        if rel.startswith(SKIP_PREFIXES):
            continue
        key = module_of(rel)
        layer, module = classify(rel)
        entry = modules.setdefault(
            key,
            {"files": 0, "lines": 0, "layers": Counter(), "largest": ("", 0)},
        )
        lines = path.read_text(encoding="utf-8", errors="replace").count("\n")
        entry["files"] += 1
        entry["lines"] += lines
        entry["layers"][(layer, module)] += 1
        if lines > entry["largest"][1]:
            entry["largest"] = (path.name, lines)
    return modules


def label(layer: str, module: str) -> str:
    if layer in (FREE, DATA):
        return layer
    return "%s/%s" % (layer, module) if module else layer


def render() -> str:
    modules = collect()
    rows = []
    for key in sorted(modules, key=lambda k: -modules[k]["lines"]):
        entry = modules[key]
        layers = ", ".join(
            label(layer, module)
            for (layer, module), _ in sorted(entry["layers"].items(), key=lambda kv: (-kv[1], kv[0]))
        )
        name, lines = entry["largest"]
        rows.append(
            "| `%s` | %s | %d | %s | `%s` (%s lines) |"
            % (key, layers, entry["files"], format(entry["lines"], ","), name, format(lines, ","))
        )

    total_files = sum(m["files"] for m in modules.values())
    total_lines = sum(m["lines"] for m in modules.values())

    out = [
        START,
        "<!-- Generated by tools/module_map.py. Do not edit between the markers: -->",
        "<!-- run `python3 tools/module_map.py` and commit the result. -->",
        "",
        "%d modules · %d files · %s lines of GDScript under `game/`."
        % (len(modules), total_files, format(total_lines, ",")),
        "",
        "| Module | Layer | Files | Lines | Largest file |",
        "| --- | --- | ---: | ---: | --- |",
    ]
    out.extend(rows)
    out.extend(["", END])
    return "\n".join(out) + "\n"


def check() -> int:
    if not DOC.exists():
        print("  %s is missing" % DOC)
        return 1
    text = DOC.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print("  %s has no %s / %s markers" % (DOC, START, END))
        return 1
    current = text[text.index(START) : text.index(END) + len(END)]
    fresh = render().strip("\n")
    if current.strip("\n") == fresh.strip("\n"):
        return 0
    print("  module map in docs/ARCHITECTURE.md is out of date:")
    old_lines = current.splitlines()
    new_lines = fresh.splitlines()
    for line in old_lines:
        if line not in new_lines:
            print("    - %s" % line)
    for line in new_lines:
        if line not in old_lines:
            print("    + %s" % line)
    print("  fix with: python3 tools/module_map.py > /tmp/map.md and paste it between the markers")
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/ARCHITECTURE.md is stale")
    args = parser.parse_args()
    if args.check:
        return check()
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
